CREATE TABLE "TIPO_DOCUMENTO" (
  "ID_documento" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre_documento" varchar(40) UNIQUE NOT NULL,
  "descripcion" varchar(150)
);

CREATE TABLE "PARENTESCO" (
  "ID_parentesco" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tipo_parentesco" varchar(50) UNIQUE NOT NULL
);

CREATE TABLE "DIRECCION" (
  "ID_direccion" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tipo_via" varchar(30),
  "nombre_via" varchar(100) NOT NULL,
  "numero" varchar(20),
  "complemento" varchar(100),
  "barrio" varchar(80),
  "ciudad" varchar(80) NOT NULL,
  "departamento" varchar(80),
  "codigo_postal" varchar(15)
);

CREATE TABLE "TELEFONO" (
  "ID_telefono" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "numero" varchar(25) UNIQUE NOT NULL,
  "indicativo" varchar(8),
  "tipo_telefono" varchar(20)
);

CREATE TABLE "PERSONA" (
  "ID_persona" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_tipo_documento" int NOT NULL,
  "numero_documento" varchar(30) NOT NULL,
  "nombre_persona" varchar(80) NOT NULL,
  "apellido_persona" varchar(100) NOT NULL,
  "fecha_nac" date,
  "correo" varchar(150)
);

CREATE TABLE "PERSONA_TELEFONO" (
  "FK_persona" int NOT NULL,
  "FK_telefono" int NOT NULL,
  PRIMARY KEY ("FK_persona", "FK_telefono")
);

CREATE TABLE "PERSONA_DIRECCION" (
  "FK_persona" int NOT NULL,
  "FK_direccion" int NOT NULL,
  "tipo_direccion" varchar(25) NOT NULL DEFAULT 'Principal',
  PRIMARY KEY ("FK_persona", "FK_direccion")
);

CREATE TABLE "EMPLEADO" (
  "ID_empleado" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_persona" int UNIQUE NOT NULL,
  "titulo_profesional" varchar(100),
  "rol_empleado" varchar(60) NOT NULL,
  "estado" varchar(20) NOT NULL DEFAULT 'Activo'
);

CREATE TABLE "ACUDIENTE" (
  "ID_acudiente" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_persona" int UNIQUE NOT NULL,
  "observaciones" varchar(250)
);

CREATE TABLE "RESIDENTE" (
  "ID_residente" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_persona" int UNIQUE NOT NULL,
  "FK_cama" int UNIQUE,
  "FK_empleado_responsable" int NOT NULL,
  "fecha_ingreso" date NOT NULL,
  "estado" varchar(25) NOT NULL DEFAULT 'Activo'
);

CREATE TABLE "RESIDENTE_ACUDIENTE" (
  "FK_residente" int NOT NULL,
  "FK_acudiente" int NOT NULL,
  "FK_parentesco" int NOT NULL,
  "es_contacto_principal" boolean NOT NULL DEFAULT false,
  "observaciones" varchar(250),
  PRIMARY KEY ("FK_residente", "FK_acudiente")
);

CREATE TABLE "ESTADO_CAMA" (
  "ID_estado_cama" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre_estado" varchar(30) UNIQUE NOT NULL
);

CREATE TABLE "HABITACION" (
  "ID_habitacion" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "piso_habitacion" int NOT NULL,
  "capacidad_maxima" int NOT NULL
);

CREATE TABLE "CAMA" (
  "ID_cama" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_habitacion" int NOT NULL,
  "FK_estado_cama" int NOT NULL,
  "codigo_cama" varchar(20) UNIQUE NOT NULL
);

CREATE TABLE "TURNO" (
  "ID_turno" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_empleado" int NOT NULL,
  "fecha" date NOT NULL,
  "hora_inicio" time NOT NULL,
  "hora_fin" time NOT NULL,
  "estado" varchar(25) NOT NULL
);

CREATE TABLE "BITACORA" (
  "ID_bitacora" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_empleado" int NOT NULL,
  "FK_habitacion" int NOT NULL,
  "fecha_hora" timestamp NOT NULL,
  "tipo_evento" varchar(60) NOT NULL,
  "descripcion" text NOT NULL,
  "estado" varchar(25),
  "nivel_prioridad" int
);

CREATE TABLE "TIPO_ACTIVIDAD" (
  "ID_tipo" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre_tipo" varchar(60) UNIQUE NOT NULL,
  "req_asistencia" boolean NOT NULL DEFAULT true,
  "observaciones" varchar(250)
);

CREATE TABLE "ACTIVIDAD" (
  "ID_actividad" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_tipo" int NOT NULL,
  "FK_empleado" int NOT NULL,
  "descripcion" varchar(250) NOT NULL,
  "cupo_maximo" int,
  "fecha_inicio" timestamp NOT NULL,
  "fecha_fin" timestamp NOT NULL,
  "estado" varchar(25) NOT NULL
);

CREATE TABLE "PARTICIPACION" (
  "ID_participacion" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_actividad" int NOT NULL,
  "FK_residente" int NOT NULL,
  "asistencia" varchar(20),
  "nivel" varchar(40),
  "observaciones" varchar(250)
);

CREATE TABLE "HISTORIAL_MEDICO" (
  "ID_historial" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_residente" int UNIQUE NOT NULL,
  "observaciones" text
);

CREATE TABLE "ENFERMEDAD" (
  "ID_enfermedad" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre_enfermedad" varchar(120) UNIQUE NOT NULL
);

CREATE TABLE "DIAGNOSTICO" (
  "ID_diagnostico" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_historial" int NOT NULL,
  "FK_enfermedad" int NOT NULL,
  "fecha_diagnostico" date NOT NULL,
  "observaciones" text
);

CREATE TABLE "ALERGIA" (
  "ID_alergia" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre_alergia" varchar(120) UNIQUE NOT NULL
);

CREATE TABLE "HISTORIAL_ALERGIA" (
  "FK_historial" int NOT NULL,
  "FK_alergia" int NOT NULL,
  "observaciones" varchar(250),
  PRIMARY KEY ("FK_historial", "FK_alergia")
);

CREATE TABLE "MEDICAMENTO" (
  "ID_medicamento" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(120) NOT NULL,
  "principio_activo" varchar(120),
  "presentacion" varchar(100),
  "concentracion" varchar(60),
  "codigo_invima" varchar(40)
);

CREATE TABLE "PRESCRIPCION" (
  "ID_prescripcion" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_historial" int NOT NULL,
  "FK_medicamento" int NOT NULL,
  "FK_diagnostico" int,
  "fecha_prescripcion" date NOT NULL,
  "fecha_fin" date,
  "dosis_indicada" decimal(10,2) NOT NULL,
  "frecuencia" varchar(100) NOT NULL,
  "indicaciones" text
);

CREATE TABLE "ADMINISTRACION_MEDICAMENTO" (
  "ID_admin_medicamento" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "FK_prescripcion" int NOT NULL,
  "FK_empleado" int NOT NULL,
  "fecha_aplicacion" timestamp NOT NULL,
  "dosis" decimal(10,2) NOT NULL,
  "descripcion" varchar(250),
  "observaciones" text
);

-- Índices únicos
CREATE UNIQUE INDEX ON "PERSONA" ("FK_tipo_documento", "numero_documento");
CREATE UNIQUE INDEX ON "PARTICIPACION" ("FK_actividad", "FK_residente");


